import { asc, eq } from 'drizzle-orm'
import { getDB } from '../db/client'
import { connections, features, projects, scenarios } from '../db/schema'
import { featureSlug } from './analysis/paths'
import { humanizeConnectionType } from '../../shared/connection-labels'

/**
 * The whole product spec as one portable Markdown document: the feature
 * tree with its scenario groups — the same content the spec UI renders,
 * scenarios on the row they live on — plus a connections appendix. Served
 * by /api/projects/:id/export/markdown as an attachment download.
 */

interface ExportGroup {
  context: string
  scenarios: Array<{ code: string, action: string, outcome: string }>
}

interface ExportFeature {
  name: string
  description: string
  groups: ExportGroup[]
  children: ExportFeature[]
}

/** Renders one feature at its heading level; children nest one level deeper. */
function renderFeature(feature: ExportFeature, level: number, lines: string[]): void {
  lines.push(`${'#'.repeat(level)} ${feature.name}`, '')
  if (feature.description) {
    lines.push(feature.description, '')
  }
  for (const group of feature.groups) {
    lines.push(`**${group.context}**`, '')
    for (const scenario of group.scenarios) {
      lines.push(`- \`${scenario.code}\` ${scenario.action} → ${scenario.outcome}`)
    }
    lines.push('')
  }
  for (const child of feature.children) {
    renderFeature(child, level + 1, lines)
  }
}

export async function exportProjectMarkdown(projectId: number): Promise<{ markdown: string, filename: string }> {
  const db = getDB()
  const project = db.select({ name: projects.name }).from(projects).where(eq(projects.id, projectId)).get()
  if (!project) {
    throw new Error(`No project with id ${projectId}`)
  }

  const featureRows = db.select({
    id: features.id,
    parentId: features.parentId,
    name: features.name,
    description: features.description,
    sortOrder: features.sortOrder,
  }).from(features).where(eq(features.projectId, projectId)).orderBy(asc(features.sortOrder), asc(features.id)).all()

  const scenarioRows = db.select({
    featureId: scenarios.featureId,
    context: scenarios.context,
    code: scenarios.code,
    action: scenarios.action,
    outcome: scenarios.outcome,
  }).from(scenarios)
    .innerJoin(features, eq(scenarios.featureId, features.id))
    .where(eq(features.projectId, projectId))
    .orderBy(asc(scenarios.sortOrder), asc(scenarios.id))
    .all()

  const connectionRows = db.select().from(connections).where(eq(connections.projectId, projectId)).all()

  // Context groups in first-seen order of the sortOrder walk — the same
  // grouping getFeatureDetail serves the spec UI.
  const groupsByFeature = new Map<number, ExportGroup[]>()
  for (const row of scenarioRows) {
    const groups = groupsByFeature.get(row.featureId) ?? []
    let group = groups.find((candidate) => candidate.context === row.context)
    if (!group) {
      group = { context: row.context, scenarios: [] }
      groups.push(group)
    }
    group.scenarios.push({ code: row.code, action: row.action, outcome: row.outcome })
    groupsByFeature.set(row.featureId, groups)
  }

  const byId = new Map(featureRows.map((row) => [row.id, {
    name: row.name,
    description: row.description,
    groups: groupsByFeature.get(row.id) ?? [],
    children: [] as ExportFeature[],
  }]))
  const roots: ExportFeature[] = []
  for (const row of featureRows) {
    const node = byId.get(row.id)!
    const parent = row.parentId ? byId.get(row.parentId) : undefined
    ;(parent ? parent.children : roots).push(node)
  }

  const nameById = new Map(featureRows.map((row) => [row.id, row.name]))
  // Directions as stored from→to; the map collapses pairs, the export keeps
  // every stored row.
  const connectionLines = connectionRows
    .flatMap((row) => {
      const from = nameById.get(row.fromFeatureId)
      const to = nameById.get(row.toFeatureId)
      return from && to ? [{ from, to, type: row.type }] : []
    })
    .sort((a, b) => a.from.localeCompare(b.from, 'en') || a.to.localeCompare(b.to, 'en') || a.type.localeCompare(b.type, 'en'))
    .map((row) => `- ${row.from} — ${humanizeConnectionType(row.type)} → ${row.to}`)

  const lines: string[] = [
    `# ${project.name}`,
    '',
    `_Generated by OpenSpecSight on ${new Date().toISOString().slice(0, 10)}: ${featureRows.length} features · ${scenarioRows.length} scenarios · ${connectionRows.length} connections._`,
    '',
  ]
  for (const root of roots) {
    renderFeature(root, 2, lines)
  }
  if (connectionLines.length > 0) {
    lines.push('## How features connect', '')
    lines.push(...connectionLines)
  }

  return {
    markdown: `${lines.join('\n')}\n`,
    filename: `${featureSlug(project.name) || 'project'}.md`,
  }
}
